-- =====================================================================
-- Modelagem da entidade ATENDIMENTO (pedido do professor)
-- Rodar DEPOIS de modelagem_pessoa.sql e modelagem_pessoa_ajuste_ficha.sql.
--
-- Corrige os relacionamentos do atendimento:
--  * pessoa 1:N atendimento  (o atendimento passa a ter id_pessoa;
--    sai a coluna invertida pessoa.id_atendimento)
--  * dados da pessoa (raça/cor, orientação etc.) ficam só em `pessoa`
--  * unidade e distrito saem da equipe (equipe -> unidade -> distrito),
--    sem repetir no atendimento
--  * domínios para tipo de atendimento e tipo de profissional
--  * distrito sanitário vira tabela, com FK em unidades_saude
--  * data E HORA do atendimento (TIMESTAMP)
--
-- HORA: SIMULADA (o mock só tem a data). Horário de funcionamento das
-- unidades, das 07:00 às 16:50, em intervalos de 10 min. Usa hashtext(),
-- então o resultado é sempre o mesmo.
--
-- mock_pec_atendimentos NÃO é alterada: continua como dado bruto.
-- Única alteração em tabela existente: FK nova em unidades_saude
-- (só a regra; nenhum dado muda).
-- =====================================================================

BEGIN;

-- ---------- Distrito sanitário ----------
CREATE TABLE distrito_sanitario (
    codigo TEXT PRIMARY KEY,
    nome   TEXT
);

INSERT INTO distrito_sanitario (codigo, nome)
SELECT DISTINCT ON (distrito_sanitario_codigo)
       distrito_sanitario_codigo, distrito_sanitario_nome
FROM unidades_saude
WHERE distrito_sanitario_codigo IS NOT NULL
ORDER BY distrito_sanitario_codigo, distrito_sanitario_nome NULLS LAST;

ALTER TABLE unidades_saude
    ADD CONSTRAINT fk_unidade_distrito
    FOREIGN KEY (distrito_sanitario_codigo) REFERENCES distrito_sanitario (codigo);

-- ---------- Domínios do atendimento ----------
CREATE TABLE tipo_atendimento (
    id_tipo_atendimento SERIAL PRIMARY KEY,
    descricao           TEXT NOT NULL UNIQUE
);

CREATE TABLE tipo_profissional (
    id_tipo_profissional SERIAL PRIMARY KEY,
    descricao            TEXT NOT NULL UNIQUE
);

INSERT INTO tipo_atendimento (descricao)
SELECT DISTINCT tipo_atendimento FROM mock_pec_atendimentos
WHERE tipo_atendimento IS NOT NULL ORDER BY 1;

INSERT INTO tipo_profissional (descricao)
SELECT DISTINCT profissional_tipo FROM mock_pec_atendimentos
WHERE profissional_tipo IS NOT NULL ORDER BY 1;

-- ---------- Pessoa: ajustes para o cadastro ----------
-- campos da ficha que são da pessoa (não do atendimento)
ALTER TABLE pessoa ADD COLUMN nome_social     TEXT;
ALTER TABLE pessoa ADD COLUMN data_nascimento DATE;   -- NULL no mock (só há idade)

UPDATE pessoa p
SET nome_social = a.nome_social
FROM mock_pec_atendimentos a
WHERE a.id_atendimento = p.id_atendimento;

-- ---------- Atendimento ----------
CREATE TABLE atendimento (
    id_atendimento        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pessoa             INTEGER   NOT NULL REFERENCES pessoa (id_pessoa),
    id_equipe             TEXT      NOT NULL REFERENCES equipes_saude (codigo_equipe),
    id_tipo_atendimento   INTEGER   REFERENCES tipo_atendimento (id_tipo_atendimento),
    id_tipo_profissional  INTEGER   REFERENCES tipo_profissional (id_tipo_profissional),
    data_hora_atendimento TIMESTAMP NOT NULL,
    idade_no_atendimento  INTEGER   CHECK (idade_no_atendimento BETWEEN 0 AND 130)
);

INSERT INTO atendimento (id_atendimento, id_pessoa, id_equipe, id_tipo_atendimento,
                         id_tipo_profissional, data_hora_atendimento, idade_no_atendimento)
SELECT a.id_atendimento,
       p.id_pessoa,
       a.codigo_equipe,
       ta.id_tipo_atendimento,
       tp.id_tipo_profissional,
       a.data_atendimento
         + make_interval(mins => (420 + (abs(hashtext('hora' || a.id_atendimento)::bigint) % 60) * 10)::int),
       a.idade
FROM mock_pec_atendimentos a
JOIN pessoa p                ON p.id_atendimento = a.id_atendimento
LEFT JOIN tipo_atendimento ta  ON ta.descricao = a.tipo_atendimento
LEFT JOIN tipo_profissional tp ON tp.descricao = a.profissional_tipo;

-- os próximos cadastros continuam a numeração
SELECT setval(pg_get_serial_sequence('atendimento', 'id_atendimento'),
              (SELECT max(id_atendimento) FROM atendimento));

-- ---------- Pessoa: corrige a relação invertida ----------
-- agora é o atendimento que aponta para a pessoa (1:N)
ALTER TABLE pessoa DROP COLUMN id_atendimento;

-- novas pessoas cadastradas pela interface ganham id automático
ALTER TABLE pessoa ALTER COLUMN id_pessoa ADD GENERATED BY DEFAULT AS IDENTITY;
SELECT setval(pg_get_serial_sequence('pessoa', 'id_pessoa'),
              (SELECT max(id_pessoa) FROM pessoa));

-- ---------- Índices ----------
CREATE INDEX idx_atend_pessoa      ON atendimento (id_pessoa);
CREATE INDEX idx_atend_equipe      ON atendimento (id_equipe);
CREATE INDEX idx_atend_data_hora   ON atendimento (data_hora_atendimento);
CREATE INDEX idx_atend_tipo        ON atendimento (id_tipo_atendimento);
CREATE INDEX idx_atend_profissional ON atendimento (id_tipo_profissional);

COMMIT;
